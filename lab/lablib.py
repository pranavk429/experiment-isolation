DEFAULT_PROJECT_NAME = "Isolation Storefront"

_SAFE_SHELL_VALUE = re.compile(r"^[A-Za-z0-9_./:@%+=,-]+$")


class LabError(RuntimeError):
    """A clear, user-facing lab failure."""


def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def load_env(path: Path = ENV_PATH) -> Dict[str, str]:
    """Load the shell-style lab/.env file, tightening permissions if needed."""
    values: Dict[str, str] = {}
    if not path.exists():
        return values
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].strip()
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        if key:
            values[key] = value
    return values


def _shell_value(value: str) -> str:
    if value == "" or _SAFE_SHELL_VALUE.match(value):
        return value
    return "'" + value.replace("'", "'\''") + "'"


def write_env(values: Dict[str, str], path: Path = ENV_PATH) -> None:
    """Atomically write lab/.env with mode 600. Never log the values."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by lab/bootstrap.py. LOCAL ONLY — never commit this file.",
        "# Load with: source lab/.env",
        "",
    ]
    for key in sorted(values):
        lines.append("export %s=%s" % (key, _shell_value(str(values[key]))))
    lines.append("")
    payload = "\n".join(lines)

    fd, tmp_name = tempfile.mkstemp(prefix=".env.", dir=str(path.parent))
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_name, path)
    finally:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)
    os.chmod(path, 0o600)


def read_json(path: Path, default: Any = None) -> Any:
    if not path.exists():
        return default
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=2, sort_keys=False)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_name, path)
    finally:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)


def _error_detail(body: bytes) -> str:
    text = body.decode("utf-8", "replace").strip()
    if not text:
        return "empty response"
    try:
        data = json.loads(text)
    except ValueError:
        return text[:400]
    if isinstance(data, dict):
        detail = data.get("detail") or data.get("message")
        if detail:
            return str(detail)[:400]
    return json.dumps(data)[:400]


def request_json(
    method: str,
    path: str,
    *,
    base_url: str,
    token: Optional[str] = None,
    api_key: Optional[str] = None,
    payload: Optional[Any] = None,
    timeout: float = 30.0,
    expected: Sequence[int] = (200, 201),
    extra_headers: Optional[Dict[str, str]] = None,
) -> Any:
    """Call the Flagsmith API and return decoded JSON (or None for 204)."""
    url = base_url.rstrip("/") + path
    data = None
    headers = {"Accept": "application/json", "User-Agent": "experiment-isolation-lab/1.0"}
    if extra_headers:
        headers.update(extra_headers)
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    if token:
        headers["Authorization"] = "Token %s" % token
    if api_key:
        headers["Authorization"] = "Api-Key %s" % api_key

    request = urllib.request.Request(url, data=data, headers=headers, method=method.upper())
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            body = response.read()
            if response.status == 204 or not body:
                return None
            return json.loads(body.decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = _error_detail(exc.read())
        raise LabError("%s %s -> HTTP %s: %s" % (method.upper(), path, exc.code, detail)) from None
    except urllib.error.URLError as exc:
        raise LabError(
            "Cannot reach %s (%s). Is the lab running? Try: bash lab/run.sh"
            % (base_url, exc.reason)
        ) from None
    except ValueError:
        raise LabError("%s %s returned non-JSON data" % (method.upper(), path)) from None


def get_list(
    path: str,
    *,
    base_url: str,
    token: Optional[str] = None,
    api_key: Optional[str] = None,
    page_size: int = 100,
) -> List[Dict[str, Any]]:
    """Return a list endpoint as a plain list (handles raw arrays and pagination)."""
    separator = "&" if "?" in path else "?"
    body = request_json(
        "GET",
        "%s%spage_size=%d" % (path, separator, page_size),
        base_url=base_url,
        token=token,
        api_key=api_key,
    )
    if isinstance(body, list):
        return body
    if isinstance(body, dict):
        results = body.get("results")
        if isinstance(results, list):
            return results
    return []


def find_by_name(items: Iterable[Dict[str, Any]], name: str) -> Optional[Dict[str, Any]]:
    wanted = name.casefold()
    for item in items:
        if str(item.get("name", "")).casefold() == wanted:
            return item
    return None


def require(value: Optional[str], message: str) -> str:
    if not value:
        raise LabError(message)
    return value


def wait_for_url(url: str, timeout: float, label: str) -> None:
    """Poll an unauthenticated URL until it returns 200."""
    deadline = time.time() + timeout
    last_error = ""
    print("Waiting for %s ..." % label)
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=5) as response:
                if response.status == 200:
                    print("  ready: %s" % url)
                    return
        except Exception as exc:  # noqa: BLE001 - keep polling any transport error
            last_error = str(exc)
        time.sleep(2)
    raise LabError(
        "%s did not become ready within %ss (last error: %s).\n"
        "  Check: docker compose -p isolation-lab -f lab/docker-compose.yml ps -a\n"
        "  Logs:  docker compose -p isolation-lab -f lab/docker-compose.yml logs --tail=40 migrate-db flagsmith"
        % (label, int(timeout), last_error or "no response")
    )


def parse_args_value(argv: Sequence[str], flag: str, default: Optional[str] = None) -> Optional[str]:
    """Tiny --flag value parser used where argparse is overkill."""
    for index, item in enumerate(argv):
        if item == flag and index + 1 < len(argv):
            return argv[index + 1]
        if item.startswith(flag + "="):
            return item.split("=", 1)[1]
    return default


def key_prefix(value: Optional[str], length: int = 6) -> str:
    if not value:
        return "(missing)"
    return value[:length] + "…"


def url_for(base_url: str, path: str) -> str:
    return urllib.parse.urljoin(base_url.rstrip("/") + "/", path.lstrip("/"))
