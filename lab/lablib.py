_SAFE_SHELL_VALUE = re.compile(r"^[A-Za-z0-9_./:@%+=,-]+$")


class LabError(RuntimeError):
    """A clear, user-facing lab failure."""


def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def load_env(path: Path = ENV_PATH) -> Dict[str, str]:
    """Load the shell-style lab/.env file, tightening permissions if needed."""
    if not path.exists():
        return {}
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass
    return parse_env_file(path)


def _shell_value(value: str) -> str:
    if value == "" or _SAFE_SHELL_VALUE.match(value):
        return value
    escaped = value.replace("'", "'\\''")
    return f"'{escaped}'"


def _atomic_write(path: Path, content: str, *, mode: Optional[int] = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f"{path.name}.", dir=str(path.parent))
    try:
        if mode is not None:
            os.fchmod(fd, mode)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp_name, path)
    finally:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)
    if mode is not None:
        os.chmod(path, mode)


def write_env(values: Dict[str, str], path: Path = ENV_PATH) -> None:
    """Atomically write lab/.env with mode 600. Never log the values."""
    lines = [
        "# Generated by lab/bootstrap.py. LOCAL ONLY — never commit this file.",
        "# Load with: source lab/.env",
        "",
        *(f"export {key}={_shell_value(str(values[key]))}" for key in sorted(values)),
        "",
    ]
    _atomic_write(path, "\n".join(lines), mode=0o600)


def read_json(path: Path, default: Any = None) -> Any:
    if not path.exists():
        return default
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def write_json(path: Path, payload: Any) -> None:
    _atomic_write(path, f"{json.dumps(payload, indent=2, sort_keys=False)}\n")


def request_json(
    method: str,
    path: str,
    *,
    base_url: str,
    token: Optional[str] = None,
    api_key: Optional[str] = None,
    payload: Optional[Any] = None,
    timeout: float = 30.0,
    expected: Sequence[int] = (200, 201),
    extra_headers: Optional[Dict[str, str]] = None,
) -> Any:
    """Call the Flagsmith API via engine.api.request_json, raising LabError."""
    del expected
    url = base_url.rstrip("/") + path
    headers: Dict[str, str] = {"User-Agent": "experiment-isolation-lab/1.0"}
    if extra_headers:
        headers.update(extra_headers)
    if token:
        headers["Authorization"] = f"Token {token}"
    if api_key:
        headers["Authorization"] = f"Api-Key {api_key}"
    secrets = tuple(
        s for s in (token, api_key, (extra_headers or {}).get("X-Environment-Key")) if s
    )
    try:
        return engine_request_json(
            method,
            url,
            headers=headers,
            payload=payload,
            timeout=timeout,
            secrets=secrets,
            safe_path=path,
        )
    except ApiError as exc:
        raise LabError(f"{method.upper()} {path} -> {exc}") from None
    except EngineError as exc:
        msg = str(exc)
        if "Cannot reach" in msg:
            raise LabError(f"{msg}. Is the lab running? Try: bash lab/run.sh") from None
        raise LabError(msg) from None


def get_list(
    path: str,
    *,
    base_url: str,
    token: Optional[str] = None,
    api_key: Optional[str] = None,
    page_size: int = 100,
) -> List[Dict[str, Any]]:
    """Return a list endpoint as a plain list (handles raw arrays and pagination)."""
    separator = "&" if "?" in path else "?"
    body = request_json(
        "GET",
        f"{path}{separator}page_size={page_size}",
        base_url=base_url,
        token=token,
        api_key=api_key,
    )
    if isinstance(body, list):
        return body
    if isinstance(body, dict) and isinstance(body.get("results"), list):
        return body["results"]
    return []


def find_by_name(items: Iterable[Dict[str, Any]], name: str) -> Optional[Dict[str, Any]]:
    wanted = name.casefold()
    for item in items:
        if str(item.get("name", "")).casefold() == wanted:
            return item
    return None


def require(value: Optional[str], message: str) -> str:
    if not value:
        raise LabError(message)
    return value


def wait_for_url(url: str, timeout: float, label: str) -> None:
    """Poll an unauthenticated URL until it returns 200."""
    deadline = time.time() + timeout
    last_error = ""
    print(f"Waiting for {label} ...")
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=5) as response:
                if response.status == 200:
                    print(f"  ready: {url}")
                    return
        except Exception as exc:  # noqa: BLE001 - keep polling any transport error
            last_error = str(exc)
        time.sleep(2)
    raise LabError(
        f"{label} did not become ready within {int(timeout)}s "
        f"(last error: {last_error or 'no response'}).\n"
        "  Check: docker compose -p isolation-lab -f lab/docker-compose.yml ps -a\n"
        "  Logs:  docker compose -p isolation-lab -f lab/docker-compose.yml logs "
        "--tail=40 migrate-db flagsmith"
    )


def parse_args_value(
    argv: Sequence[str], flag: str, default: Optional[str] = None
) -> Optional[str]:
    """Tiny --flag value parser used where argparse is overkill."""
    for index, item in enumerate(argv):
        if item == flag and index + 1 < len(argv):
            return argv[index + 1]
        if item.startswith(f"{flag}="):
            return item.split("=", 1)[1]
    return default


def key_prefix(value: Optional[str], length: int = 6) -> str:
    if not value:
        return "(missing)"
    return f"{value[:length]}…"


def url_for(base_url: str, path: str) -> str:
    return urllib.parse.urljoin(f"{base_url.rstrip('/')}/", path.lstrip("/"))
